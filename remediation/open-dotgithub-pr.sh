#!/usr/bin/env bash
# Opens the .github tracking issue and LICENSE pull request from the generated
# drafts, the same way every other repository's were opened. Agent sessions
# cannot reach a repository whose name begins with a dot, so the apply-settings
# workflow runs this with the owner's token. It is idempotent: an open issue
# or pull request that already exists is reused, never duplicated.
#
#   GH_TOKEN=<token> remediation/open-dotgithub-pr.sh
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
repo=UOR-Foundation/.github
title='Bring .github up to the repository standards'
work=$(mktemp -d)

issue=$(gh issue list -R "$repo" --state open --search "in:title \"$title\"" --json number,title --jq ".[] | select(.title == \"$title\") | .number" | head -1)
if [ -z "$issue" ]; then
  awk 'n >= 2 { print; next } /^---$/ { n++ }' "$here/drafts/.github.issue.md" | sed '1{/^$/d}' > "$work/issue.md"
  url=$(gh issue create -R "$repo" --title "$title" --body-file "$work/issue.md" --label enhancement 2>/dev/null \
    || gh issue create -R "$repo" --title "$title" --body-file "$work/issue.md")
  issue=${url##*/}
fi
echo "issue #$issue"

branch="chore/$issue-repository-standards"
existing=$(gh pr list -R "$repo" --head "$branch" --state open --json url --jq '.[0].url // empty')
if [ -n "$existing" ]; then echo "pull request $existing"; exit 0; fi

login=$(gh api user --jq .login); id=$(gh api user --jq .id)
git clone -q --depth 1 "https://x-access-token:$GH_TOKEN@github.com/$repo.git" "$work/repo"
cd "$work/repo"
git checkout -q -B "$branch"
node "$here/write-pr.mjs" .github "$work/repo"
git add -A
git -c user.name="$login" -c user.email="$id+$login@users.noreply.github.com" \
  commit -q -m "chore: bring repository up to UOR-Foundation standards" \
  -m "Adds the files GOVERNANCE.md 6.1 requires, generated by UOR-Foundation/community remediation/write-pr.mjs from remediation/register.json."
git push -q --force-with-lease -u origin "$branch"
{
  sed "s/{issue}/$issue/g" "$here/drafts/.github.pr.md"
  printf '\n---\nOpened by the apply-settings workflow of UOR-Foundation/community.\n'
} > "$work/pr.md"
gh pr create -R "$repo" --head "$branch" --base "$(gh repo view "$repo" --json defaultBranchRef --jq .defaultBranchRef.name)" \
  --title "chore: bring repository up to UOR-Foundation standards" --body-file "$work/pr.md"
